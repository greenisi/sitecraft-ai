/**
 * The questions worth asking once a site exists.
 *
 * The intake deliberately builds first and asks nothing, which is right for
 * the wow-moment but leaves the model inventing the things it could not know:
 * a wordmark when the owner already has a logo, a phone number, opening hours,
 * neighbourhoods it serves. And nobody ever asked where leads should be sent,
 * so alerts went to whatever address the account was signed up with.
 *
 * Two kinds of question:
 *
 *  - PRACTICAL: logo, lead email, phone, hours, service area. Same for every
 *    business, each one changing something concrete on the site or in the
 *    plumbing behind it.
 *  - PROBING: what the owner actually does and what they need the site to do.
 *    These are per-trade, because "what's your busiest service?" is a useful
 *    question for a roofer and a meaningless one for a law firm.
 *
 * The probing set is derived from the trade rather than generated by a model.
 * That keeps this working with no API key, no spend and no latency, and the
 * questions stay good because they were written for the trade rather than
 * improvised per request.
 */

export type FollowUpKind = 'text' | 'longtext' | 'email' | 'tel' | 'logo' | 'hours';

export interface FollowUpQuestion {
  id: string;
  label: string;
  /** Shown under the label — why we're asking, in the owner's terms. */
  help?: string;
  kind: FollowUpKind;
  placeholder?: string;
  required?: boolean;
}

