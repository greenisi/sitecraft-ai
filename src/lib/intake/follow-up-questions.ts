export interface FollowUpSet {
  probing: FollowUpQuestion[];
  practical: FollowUpQuestion[];
}

export function buildFollowUpQuestions(input: {
  industry?: string;
  description?: string;
  siteType?: string;
}): FollowUpSet {
  const haystack = [input.industry, input.description, input.siteType].filter(Boolean).join(' ');
  const probe = PROBES.find((entry) => entry.match.test(haystack));
  return {
    probing: probe ? probe.questions : DEFAULT_PROBES,
    practical: PRACTICAL,
  };
}

